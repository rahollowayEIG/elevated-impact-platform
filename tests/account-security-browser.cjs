const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { mkdir } = require('node:fs/promises');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const base = 'http://127.0.0.1:4198/tests/account-security.html';
  const writes = () => page.evaluate(() => window.securityFixture.calls.filter((row) => row.action === 'admin_session_signout'));
  const open = async () => { await page.goto(base); await page.getByText('2 matches', { exact: true }).waitFor(); };
  const confirm = async () => {
    await page.getByRole('button', { name: 'Sign Out All Sessions', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Reason', { exact: true }).fill('Synthetic security test');
    await dialog.getByRole('checkbox').check();
    return dialog;
  };
  try {
    await open();
    assert.equal(await page.locator('vite-error-overlay').count(), 0);
    await page.getByLabel('Search account history').fill('Kellie');
    await page.getByText('1 matches', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Clear', exact: true }).click();
    await page.getByRole('button', { name: 'When ↓', exact: true }).click();
    assert.equal(await page.locator('tbody tr').first().locator('td').nth(2).innerText(), 'Ryan\nadmin');
    await page.getByRole('button', { name: 'When ↑', exact: true }).click();
    assert.equal(await page.locator('tbody tr').first().locator('td').nth(2).innerText(), 'Kellie\nadmin-two');
    await page.getByRole('button', { name: 'Sign Out All Sessions', exact: true }).click();
    await page.getByRole('dialog').getByText('avery@example.test', { exact: true }).waitFor();
    assert.equal(await page.getByRole('dialog').getByRole('button', { name: 'Sign Out All Sessions', exact: true }).isDisabled(), true);
    await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.equal((await writes()).length, 0);
    assert.equal(await page.locator('#account-signout-button').evaluate((node) => node === document.activeElement), true);
    await page.evaluate(() => { window.securityFixture.delay = 150; });
    const dialog = await confirm();
    await dialog.getByRole('button', { name: 'Sign Out All Sessions', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Revoked 2' }).waitFor();
    await page.getByText('3 matches', { exact: true }).waitFor();
    const sent = await writes(); assert.equal(sent.length, 1); assert.equal(sent[0].target_user_id, sent[0].confirmation); assert.equal(sent[0].reason, 'Synthetic security test');
    await mkdir('test-results/account-security', { recursive: true });
    await page.screenshot({ path: 'test-results/account-security/desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'test-results/account-security/mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await open(); await page.evaluate(() => window.setSecuritySelf(true));
    await page.waitForFunction(() => document.getElementById('account-signout-button').disabled);
    assert.equal((await writes()).length, 0);
    await open(); await page.evaluate(() => { window.securityFixture.fail = true; });
    const failing = await confirm(); await failing.getByRole('button', { name: 'Sign Out All Sessions', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Synthetic network uncertainty' }).waitFor();
    assert.equal(await page.locator('#account-signout-button').isDisabled(), true);
    assert.equal((await writes()).length, 1);
    await page.getByRole('button', { name: 'Refresh History' }).click();
    assert.equal((await writes()).length, 1);
    await page.evaluate(() => window.selectSecurityTarget(2));
    await page.waitForFunction(() => !document.getElementById('account-signout-button').disabled);
    const second = await confirm(); await second.getByText('other@example.test', { exact: true }).waitFor();
    await second.getByRole('button', { name: 'Cancel', exact: true }).click();
    await open();
    await page.evaluate(() => { window.securityFixture.historyFail = true; });
    await page.getByRole('button', { name: 'Refresh History' }).click();
    await page.getByRole('alert').filter({ hasText: 'Synthetic history failure' }).waitFor();
    assert.equal(await page.getByText('History unavailable', { exact: true }).count(), 1);
    assert.equal(await page.getByText('No recorded account changes yet.', { exact: true }).count(), 0);
    assert.equal(await page.getByText('0 matches', { exact: true }).count(), 0);
    assert.equal(await page.getByLabel('Search account history').isDisabled(), true);
    await page.evaluate(() => { window.securityFixture.historyFail = false; });
    await page.getByRole('button', { name: 'Refresh History' }).click();
    await page.getByText('2 matches', { exact: true }).waitFor();
    assert.equal(await page.getByRole('alert').count(), 0);
    assert.deepEqual(errors, []);
    console.log('PASS: history search/sort, exact-account dialog, required reason, cancellation/focus, single request, durable history refresh, mobile overflow, self protection, uncertain-request lock, same-name distinction; no browser errors.');
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
